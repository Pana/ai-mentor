/** 阝在左边是“左耳刀”（多和山坡、地势有关），在右边是“右耳刀”（多和城镇、地方有关）。 */
function earKnife(strokes) {
  return strokes?.[0] === 0 ? ['左耳刀', '和山坡、地势有关'] : ['右耳刀', '和城镇、地方有关'];
}

/** 字 → { radical, radicalName, radicalMeaning }；字本身就是部首时叫法写“本身就是部首”。 */
export function radicalInfo(char, radical, strokes) {
  if (radical === char) return { radical, radicalName: '本身就是部首', radicalMeaning: NAMES[radical]?.[1] ?? '' };
  const [name, meaning] = radical === '阝' ? earKnife(strokes) : NAMES[radical] ?? ['', ''];
  return { radical, radicalName: name, radicalMeaning: meaning };
}
